import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile


with tempfile.TemporaryDirectory(prefix="np-shortcut-icons-") as temporary:
    root = Path(temporary)
    run = root / "Applications/Game.app/Contents/MacOS/run.sh"
    run.parent.mkdir(parents=True)
    run.write_text('#!/bin/bash\n# autogenerated file - do not edit\n\nopen steam://run/100\n\n')
    icon = root / "Applications/Game.app/Contents/Resources/shortcut.icns"
    icon.parent.mkdir()
    icon.write_bytes(b"old icon")
    shutil.copytree(root / "Applications", root / "Desktop")
    desktop_icon = root / "Desktop/Game.app/Contents/Resources/shortcut.icns"
    desktop_icon.write_bytes(b"user icon")

    support = root / "Library/Application Support/notproton"
    support.mkdir(parents=True)
    (support / "appinfo").write_text("#!/bin/sh\nprintf 'name=Game\\nicon=abc123\\n'\n")
    (support / "iconmaker").write_text(
        '#!/bin/sh\nif [ "$1" = --shortcuts ]; then exec "$REAL_ICONMAKER" "$@"; fi\ncp "$1" "$2"\n')
    for helper in ("appinfo", "iconmaker"):
        (support / helper).chmod(0o755)
    steam = root / "Steam"
    client = steam / "Steam.AppBundle/Steam/Contents/MacOS"
    client.mkdir(parents=True)
    (steam / "appcache").mkdir()
    (steam / "appcache/appinfo.vdf").write_bytes(b"vdf")
    art = steam / "appcache/librarycache/100/abc123.jpg"
    art.parent.mkdir(parents=True)
    art.write_bytes(b"game art")
    stock = client / "steam.icns"
    stock.write_bytes(b"old icon")
    env = dict(os.environ, HOME=str(root), REAL_ICONMAKER=str(Path(sys.argv[1]).resolve()))
    for app_id in ("", "0", "01x", "1;2"):
        assert subprocess.run(["/bin/sh", "dylib/feats/compat_run.sh", "shortcut-icons", app_id, str(client)],
                               env=env, timeout=5).returncode == 1
    assert subprocess.run(["/bin/sh", "dylib/feats/compat_run.sh", "shortcut-icons", "100", "relative/MacOS"],
                           env=env, timeout=5).returncode == 1
    subprocess.run(["/bin/sh", "dylib/feats/compat_run.sh", "shortcut-icons", "100", str(client)],
                   env=env, check=True, timeout=10)
    assert icon.read_bytes() == b"game art"
    assert desktop_icon.read_bytes() == b"user icon"
    assert (support / "shortcut-icons/100/game.icns").read_bytes() == b"game art"
    assert not (support / "launchers").exists()

    stock_run = "#!/bin/bash\n# autogenerated file - do not edit\n\nopen steam://run/-1832369722\n\n"
    fixed_run = "#!/bin/bash\n# autogenerated file - do not edit\n\nopen steam://rungameid/10576776043572494336\n\n"

    def shortcut(folder, name, run_text, icon_bytes):
        app = root / folder / f"{name}.app"
        (app / "Contents/MacOS").mkdir(parents=True)
        (app / "Contents/Resources").mkdir()
        (app / "Contents/MacOS/run.sh").write_text(run_text)
        (app / "Contents/Resources/shortcut.icns").write_bytes(icon_bytes)
        return app

    def fix(*arguments):
        return subprocess.run(["/bin/sh", "dylib/feats/compat_run.sh", "shortcut-fix", *arguments],
                              env=env, timeout=10).returncode

    def state(app):
        return (app / "Contents/MacOS/run.sh").read_text(), (app / "Contents/Resources/shortcut.icns").read_bytes()

    (support / "iconmaker").write_text(
        '#!/bin/sh\ncase "$2" in *.icns) ;; *) exit 1 ;; esac\ncase "$(cat "$1")" in MZgood*) printf made > "$2" ;; *) exit 1 ;; esac\n')
    game = shortcut("Desktop", "Windows Game", stock_run, b"MZgood exe")
    plain = shortcut("Applications", "No Icon", stock_run, b"MZbad exe")
    custom = shortcut("Desktop", "Custom Icon", stock_run, b"png art")
    edited = shortcut("Desktop", "Edited", stock_run + "echo mine\n", b"MZgood exe")
    other = shortcut("Desktop", "Other Game", stock_run.replace("-1832369722", "-5"), b"MZgood exe")
    steam_game = shortcut("Desktop", "Steam Game", stock_run.replace("-1832369722", "100"), b"MZgood exe")
    for arguments in (("", "10576776043572494336", str(client)), ("100", "10576776043572494336", str(client)),
                      ("4294967296", "10576776043572494336", str(client)), ("2462597574", "", str(client)),
                      ("2462597574", "1;2", str(client)), ("2462597574", "10576776043572494336", "relative")):
        assert fix(*arguments) == 1
    assert state(game) == (stock_run, b"MZgood exe")
    assert fix("2462597574", "10576776043572494336", str(client)) == 0
    assert state(game) == (fixed_run, b"made")
    assert (game / "Contents/MacOS/run.sh").stat().st_mode & 0o111
    assert state(plain) == (fixed_run, b"old icon")
    assert state(custom) == (fixed_run, b"png art")
    assert state(edited) == (stock_run + "echo mine\n", b"MZgood exe")
    assert state(other) == (stock_run.replace("-1832369722", "-5"), b"MZgood exe")
    assert state(steam_game) == (stock_run.replace("-1832369722", "100"), b"MZgood exe")
    assert [p.name for p in root.rglob("*.notproton*")] == []
    assert fix("2462597574", "10576776043572494336", str(client)) == 0
    assert state(game) == (fixed_run, b"made")

print("shortcut-launch: Steam-made shortcuts get artwork, custom icons and bad arguments are left alone, non-Steam shortcuts open by game ID with a real icon")
